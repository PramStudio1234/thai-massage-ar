def table(headers, rows, widths):
    t = doc.add_table(rows=1, cols=len(headers))
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    for c,w in zip(t.columns,widths): c.width=Cm(w)
    for c,txt in zip(t.rows[0].cells,headers): c.text=txt
    rep=OxmlElement('w:tblHeader');t.rows[0]._tr.get_or_add_trPr().append(rep)
    for row in rows:
        for c,txt in zip(t.add_row().cells,row): c.text=txt
    for ri,row in enumerate(t.rows):
        for ci,c in enumerate(row.cells):
            c.width=Cm(widths[ci]);c.vertical_alignment=WD_CELL_VERTICAL_ALIGNMENT.CENTER
            tc=c._tc.get_or_add_tcPr()
            sh=OxmlElement('w:shd');sh.set(qn('w:fill'),'E6EDF2' if ri==0 else ('F6F8FA' if ri%2==0 else 'FFFFFF'));tc.append(sh)
            bd=OxmlElement('w:tcBorders')
            for edge in ['top','left','bottom','right']:
                e=OxmlElement('w:'+edge);e.set(qn('w:val'),'single');e.set(qn('w:sz'),'4');e.set(qn('w:color'),'D9D9D9');bd.append(e)
            tc.append(bd)
            mar=OxmlElement('w:tcMar')
            for edge in ['top','left','bottom','right']:
                e=OxmlElement('w:'+edge);e.set(qn('w:w'),'110');e.set(qn('w:type'),'dxa');mar.append(e)
            tc.append(mar)
            for para in c.paragraphs:
                para.paragraph_format.space_after=Pt(2)
                for r in para.runs:
                    r.font.size=Pt(11);r.bold=ri==0
    doc.add_paragraph().paragraph_format.space_after=Pt(0)
    return t

